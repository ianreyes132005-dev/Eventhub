-- Persist admin announcement-removal notices for organizers.
-- The function removes the announcement and creates its notice atomically.

CREATE TABLE IF NOT EXISTS public.notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text NOT NULL,
  user_type text NOT NULL CHECK (user_type IN ('student', 'organizer')),
  title varchar(200) NOT NULL,
  message text NOT NULL,
  is_read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.notifications
  ADD COLUMN IF NOT EXISTS notification_type text;

CREATE INDEX IF NOT EXISTS notifications_organizer_type_created_idx
  ON public.notifications (user_id, user_type, notification_type, created_at DESC);

ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "organizer_select_own_notifications"
  ON public.notifications;
CREATE POLICY "organizer_select_own_notifications"
  ON public.notifications
  FOR SELECT TO authenticated
  USING (
    user_type = 'organizer'
    AND user_id = (
      SELECT o.organizer_id::text
      FROM public.organizers o
      WHERE o.user_id = auth.uid()
    )
  );

GRANT SELECT ON public.notifications TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_delete_announcement(
  p_announcement_id integer,
  p_reason text
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  announcement_row public.announcements%ROWTYPE;
  recipient_id text;
  reason_text text := btrim(COALESCE(p_reason, ''));
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.admins WHERE user_id = auth.uid()
  ) THEN
    RAISE EXCEPTION 'Only an administrator can remove announcements.';
  END IF;

  IF reason_text = '' THEN
    RAISE EXCEPTION 'A removal reason is required.';
  END IF;

  SELECT *
  INTO announcement_row
  FROM public.announcements
  WHERE id = p_announcement_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'The announcement no longer exists.';
  END IF;

  SELECT o.organizer_id::text
  INTO recipient_id
  FROM public.organizers o
  WHERE o.user_id = announcement_row.created_by;

  IF recipient_id IS NULL THEN
    RAISE EXCEPTION 'Could not find the organizer who posted this announcement.';
  END IF;

  INSERT INTO public.notifications (
    user_id, user_type, title, message, notification_type
  )
  VALUES (
    recipient_id,
    'organizer',
    'Announcement removed',
    format(
      'Your announcement "%s" was removed by an administrator. Reason: %s',
      announcement_row.title,
      reason_text
    ),
    'announcement_deleted'
  );

  DELETE FROM public.announcements
  WHERE id = p_announcement_id;

  RETURN true;
END;
$$;

REVOKE ALL ON FUNCTION public.admin_delete_announcement(integer, text)
  FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_delete_announcement(integer, text)
  TO authenticated;
